const LANGUAGE_OVERRIDES: Record<DisplayLanguage, Partial<TranslationDictionary>> = {
  en: {},
  ko: KO_STRINGS,
  ja: JA_STRINGS,
};

function isDisplayLanguage(value: string | undefined): value is DisplayLanguage {
  return !!value && SUPPORTED_DISPLAY_LANGUAGES.includes(value as DisplayLanguage);
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) { return template; }
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
}

export class LocalizationService {
  public static getDisplayLanguage(): DisplayLanguage {
    const configured = vscode.workspace.getConfiguration('arc-client').get<string>('displayLanguage', DEFAULT_LANGUAGE);
    return isDisplayLanguage(configured) ? configured : DEFAULT_LANGUAGE;
  }

  public static getDateLocale(language: DisplayLanguage = LocalizationService.getDisplayLanguage()): string {
    return DATE_LOCALES[language] ?? DATE_LOCALES[DEFAULT_LANGUAGE];
  }

  public static getDisplayLanguageLabel(language: DisplayLanguage): string {
    return DISPLAY_LANGUAGE_LABELS[language] ?? DISPLAY_LANGUAGE_LABELS[DEFAULT_LANGUAGE];
  }

  public static getStrings(language: DisplayLanguage = LocalizationService.getDisplayLanguage()): TranslationDictionary {
    return {
      ...EN_STRINGS,
      ...((LANGUAGE_OVERRIDES[language] ?? {}) as TranslationDictionary),
    };
  }

  public static t(
    key: string,
    params?: Record<string, string | number>,
    language: DisplayLanguage = LocalizationService.getDisplayLanguage()
  ): string {
    const dictionary = LocalizationService.getStrings(language);
    return interpolate(dictionary[key] ?? EN_STRINGS[key] ?? key, params);
  }

  public static formatDateTime(date: Date, language: DisplayLanguage = LocalizationService.getDisplayLanguage()): string {
    try {
      return new Intl.DateTimeFormat(LocalizationService.getDateLocale(language), {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
      }).format(date);
    } catch {
      return date.toISOString();
    }
  }
}
